import pandas as pd

# 1. الأقسام (8 أقسام من مستويات مختلفة)
classes = {
    'اسم القسم': ['1م1', '1م2', '2م1', '2م2', '3م1', '3م2', '4م1', '4م2'],
    'المستوى': ['1 متوسط', '1 متوسط', '2 متوسط', '2 متوسط', '3 متوسط', '3 متوسط', '4 متوسط', '4 متوسط'],
    'الشعبة': ['-']*8,
    'عدد التلاميذ': [35, 34, 32, 33, 30, 31, 28, 29]
}

# 2. الأساتذة (تمت إضافة أساتذة مساعدين لتخفيف العبء)
teachers = {
    'اسم الأستاذ': ['أحمد (رياضيات)', 'كمال (رياضيات 2)', 'فاطمة (عربية)', 'زينب (عربية 2)', 'عمر (علوم)', 'سارة (فيزياء)', 'علي (فرنسية)', 'مريم (إنجليزية)', 'يوسف (تاريخ)', 'خديجة (إسلامية)', 'طارق (رياضة)', 'هدى (رسم)'],
    'المادة': ['رياضيات', 'رياضيات', 'لغة عربية', 'لغة عربية', 'علوم طبيعة وحياة', 'علوم فيزيائية', 'لغة فرنسية', 'لغة إنجليزية', 'تاريخ وجغرافيا', 'تربية إسلامية', 'تربية بدنية', 'تربية تشكيلية'],
    'النصاب الأقصى': [22]*12,
    'الرتبة': ['أساسي']*12,
    'الأيام المحظورة': ['الإثنين', '', 'الخميس صباحا', '', '', '', '', '', '', '', '', '']
}

# 3. إسناد الحصص (توزيع عادل)
assignments = []
for i, c in enumerate(classes['اسم القسم']):
    # أحمد وفاطمة يدرسون أول 4 أقسام، وكمال وزينب يدرسون الباقي
    math_teacher = 'أحمد (رياضيات)' if i < 4 else 'كمال (رياضيات 2)'
    arabic_teacher = 'فاطمة (عربية)' if i < 4 else 'زينب (عربية 2)'
    
    assignments.append([ math_teacher, c, 'رياضيات', 4, 0, 'لا يوجد' ])
    assignments.append([ arabic_teacher, c, 'لغة عربية', 5, 0, 'لا يوجد' ])
    assignments.append([ 'عمر (علوم)', c, 'علوم طبيعة وحياة', 2, 0, 'لا يوجد' ])
    assignments.append([ 'سارة (فيزياء)', c, 'علوم فيزيائية', 2, 0, 'لا يوجد' ])
    assignments.append([ 'علي (فرنسية)', c, 'لغة فرنسية', 3, 0, 'لا يوجد' ])
    assignments.append([ 'مريم (إنجليزية)', c, 'لغة إنجليزية', 2, 0, 'لا يوجد' ])
    assignments.append([ 'يوسف (تاريخ)', c, 'تاريخ وجغرافيا', 2, 0, 'لا يوجد' ])
    assignments.append([ 'خديجة (إسلامية)', c, 'تربية إسلامية', 1, 0, 'لا يوجد' ])
    assignments.append([ 'طارق (رياضة)', c, 'تربية بدنية', 2, 0, 'لا يوجد' ])

df_assign = pd.DataFrame(assignments, columns=['الأستاذ', 'القسم', 'المادة', 'حصص فردية (1سا)', 'حصص مزدوجة (2سا)', 'نوع التفويج'])

# توليد الملف
file_name = 'real_school_data.xlsx'
with pd.ExcelWriter(file_name, engine='openpyxl') as writer:
    pd.DataFrame(classes).to_excel(writer, sheet_name='الأقسام', index=False)
    pd.DataFrame(teachers).to_excel(writer, sheet_name='الأساتذة', index=False)
    df_assign.to_excel(writer, sheet_name='الإسناد', index=False)

print(f"✅ تم توليد ملف المؤسسة المتوازن: {file_name}")